mod support;
use std::fs;
fn program(id: &str) {
    let root = support::root().join("tests/programs");
    let path = root.join(format!("{id}.lume"));
    let expected = root.join(format!("{id}.stdout"));
    let scratch = support::Scratch::new();
    let outputs: Vec<_> = (0..3)
        .map(|level| {
            let compiled =
                lumec::compile_path(&path, level).unwrap_or_else(|errors| panic!("{}", errors[0]));
            let out = scratch.join(&format!("O{level}.wasm"));
            fs::write(&out, compiled.wasm).unwrap();
            out
        })
        .collect();
    support::node(
        "tools/check_variants.cjs",
        &[&outputs[0], &outputs[1], &outputs[2], &expected],
    );
}
